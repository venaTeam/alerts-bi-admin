"""Acceptance verification (design section 7.5, acceptance-data contract).

Runs the acceptance teams against the mock and compares the PERSISTED SQL rows and the
rendered CSV exports against ``test/fixtures/expected-results.json``.

The manifest is hand-authored from the fixture definitions and is never generated by this
pipeline: an oracle produced by the code under test would agree with any bug that happened
to be self-consistent. It is also carried over from the JavaScript implementation
unchanged, which is what lets it detect a behavioural difference introduced by the port.
"""

